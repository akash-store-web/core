-- Decisiones (15-oct-2026):
--   * El stock solo cambia por movimientos: inventario_inicial, compra, venta o ajuste.
--   * Todo producto o variante nace con existencias 0; entra por compra (con comprobante).
--   * Cada línea de compra guarda el costo unitario (obligatorio).
--   * Proveedor como texto en la compra, con RUC opcional. Duplicado = mismo proveedor + tipo + número.
--   * variante.existencias se mantiene como saldo actual; movimiento_stock es su historial
--     (cada movimiento guarda el saldo resultante).
--
-- Es transaccional: si algo falla, no queda nada a medias. Solo CREA tablas; no modifica las existentes.
-- =====================================================================================
BEGIN;

-- ---------- HU033: compra de mercadería ----------
CREATE TABLE IF NOT EXISTS public.compra (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor           VARCHAR(120) NOT NULL,
    proveedor_ruc       VARCHAR(11)  NULL,                 -- 11 dígitos; opcional (boletas)
    tipo_comprobante    VARCHAR(10)  NOT NULL,             -- 'boleta' | 'factura'
    numero_comprobante  VARCHAR(30)  NOT NULL,             -- p. ej. F001-000123
    fecha               DATE         NOT NULL,             -- fecha del comprobante
    comprobante_url     VARCHAR(255) NULL,                 -- ruta en el bucket privado (AKASH-115)
    total               NUMERIC(10,2) NOT NULL,            -- suma de cantidad × costo_unitario
    usuario_id          INTEGER      NULL,                 -- quién la registró
    creado_en           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_compra_tipo CHECK (tipo_comprobante IN ('boleta', 'factura')),
    CONSTRAINT ck_compra_ruc CHECK (proveedor_ruc IS NULL OR proveedor_ruc ~ '^[0-9]{11}$'),
    CONSTRAINT ck_compra_total CHECK (total >= 0),
    CONSTRAINT fk_compra_usuario FOREIGN KEY (usuario_id) REFERENCES public.usuario(id)
);
-- Escenario 5 de HU033: no se puede registrar dos veces el mismo comprobante del mismo proveedor.
CREATE UNIQUE INDEX IF NOT EXISTS ux_compra_comprobante
    ON public.compra (lower(proveedor), tipo_comprobante, upper(numero_comprobante));

CREATE TABLE IF NOT EXISTS public.detalle_compra (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id       INTEGER       NOT NULL,
    variante_id     INTEGER       NOT NULL,
    cantidad        INTEGER       NOT NULL,
    costo_unitario  NUMERIC(10,2) NOT NULL,
    CONSTRAINT ck_detalle_compra_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_compra_costo CHECK (costo_unitario >= 0),
    CONSTRAINT fk_detalle_compra_compra FOREIGN KEY (compra_id) REFERENCES public.compra(id),
    CONSTRAINT fk_detalle_compra_variante FOREIGN KEY (variante_id) REFERENCES public.variante(id)
);
CREATE INDEX IF NOT EXISTS ix_detalle_compra_compra ON public.detalle_compra (compra_id);
CREATE INDEX IF NOT EXISTS ix_detalle_compra_variante ON public.detalle_compra (variante_id);

-- ---------- HU034: movimientos de stock ----------
CREATE TABLE IF NOT EXISTS public.movimiento_stock (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variante_id  INTEGER      NOT NULL,
    tipo         VARCHAR(20)  NOT NULL,      -- inventario_inicial | compra | venta | ajuste
    cantidad     INTEGER      NOT NULL,      -- con signo: + entra, − sale
    saldo        INTEGER      NOT NULL,      -- existencias de la variante después del movimiento
    motivo       VARCHAR(200) NULL,          -- obligatorio en los ajustes
    compra_id    INTEGER      NULL,          -- referencia cuando tipo = compra
    pedido_id    INTEGER      NULL,          -- referencia cuando tipo = venta (HU010/HU018)
    usuario_id   INTEGER      NULL,          -- quién lo registró (NULL = sistema)
    fecha        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('inventario_inicial', 'compra', 'venta', 'ajuste')),
    CONSTRAINT ck_movimiento_cantidad CHECK (cantidad <> 0),
    CONSTRAINT ck_movimiento_saldo CHECK (saldo >= 0),
    CONSTRAINT ck_movimiento_ajuste_motivo CHECK (tipo <> 'ajuste' OR length(trim(motivo)) > 0),
    CONSTRAINT ck_movimiento_compra CHECK (tipo <> 'compra' OR compra_id IS NOT NULL),
    CONSTRAINT fk_movimiento_variante FOREIGN KEY (variante_id) REFERENCES public.variante(id),
    CONSTRAINT fk_movimiento_compra FOREIGN KEY (compra_id) REFERENCES public.compra(id),
    CONSTRAINT fk_movimiento_pedido FOREIGN KEY (pedido_id) REFERENCES public.pedido(id),
    CONSTRAINT fk_movimiento_usuario FOREIGN KEY (usuario_id) REFERENCES public.usuario(id)
);
CREATE INDEX IF NOT EXISTS ix_movimiento_variante_fecha ON public.movimiento_stock (variante_id, fecha);

-- ---------- Seguridad: igual que el resto de tablas (acceso solo vía FastAPI) ----------
ALTER TABLE public.compra           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalle_compra   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.movimiento_stock ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON public.compra, public.detalle_compra, public.movimiento_stock FROM anon, authenticated;

COMMIT;

